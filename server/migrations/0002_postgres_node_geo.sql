-- 0002 节点地理位置
--
-- 为什么要新增经纬度：世界地图打点需要城市级坐标，
-- 仅有 geo_country 的话所有欧洲节点会挤在国家中心点上。
--
-- 坐标来源优先级：
--   1. geo_cache 内置表（覆盖主要城市，无外部请求）
--   2. 服务端按 IP 解析后落库
--   精度到城市中心，足以在地图上定位，不足以定位到具体机房。

ALTER TABLE nodes ADD COLUMN geo_lat REAL;
ALTER TABLE nodes ADD COLUMN geo_lon REAL;

-- 坐标缓存：解析服务有速率限制且可能失败，解析一次后落库，
-- 避免每次刷状态页都去查。
CREATE TABLE IF NOT EXISTS geo_cache (
    country_code VARCHAR(8)  NOT NULL,
    city        VARCHAR(64) NOT NULL,
    lat         REAL         NOT NULL,
    lon         REAL         NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    PRIMARY KEY (country_code, city)
);

